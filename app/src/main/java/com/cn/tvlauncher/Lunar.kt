    private val BASE = LocalDate.of(1900, 1, 31)
    private val MON = arrayOf("正", "二", "三", "四", "五", "六", "七", "八", "九", "十", "冬", "腊")
    private val TEN = arrayOf("初", "十", "廿", "三")
    private val NUM = arrayOf("一", "二", "三", "四", "五", "六", "七", "八", "九", "十")

    data class LDate(val year: Int, val month: Int, val day: Int, val leap: Boolean)

    private fun leapMonth(y: Int) = INFO[y - 1900] and 0xf
    private fun monthDays(y: Int, m: Int) = if (INFO[y - 1900] and (1 shl (4 + m)) != 0) 30 else 29
    private fun leapDays(y: Int) = if (leapMonth(y) == 0) 0 else if (INFO[y - 1900] and 16 != 0) 30 else 29
    fun yearDays(y: Int) = (1..12).sumOf { monthDays(y, it) } + leapDays(y)

    fun of(d: LocalDate): LDate {
        var off = ChronoUnit.DAYS.between(BASE, d).toInt()
        require(off >= 0) { "超出范围" }
        var y = 1900
        while (y < 2100 && off >= yearDays(y)) { off -= yearDays(y); y++ }
        val lm = leapMonth(y)
        for (m in 1..12) {
            val md = monthDays(y, m)
            if (off < md) return LDate(y, m, off + 1, false)
            off -= md
            if (m == lm) {
                val ld = leapDays(y)
                if (off < ld) return LDate(y, m, off + 1, true)
                off -= ld
            }
        }
        error("农历计算越界")
    }

    fun dayName(d: Int) = when (d) { 10 -> "初十"; 20 -> "二十"; 30 -> "三十"; else -> TEN[d / 10] + NUM[(d - 1) % 10] }
    fun text(d: LocalDate): String = runCatching { val l = of(d); "农历" + (if (l.leap) "闰" else "") + MON[l.month - 1] + "月" + dayName(l.day) }.getOrDefault("")
}
